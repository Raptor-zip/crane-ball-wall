/** Replay text of a q sequence: b64url(encodeReplay) with device Unknown, no flags, the current SIM_VERSION. */
export function replayText(phys: LevelPhysics, qs: Int8Array): string {
  return b64urlEncode(encodeReplay({ fmt: 1, sim: SIM_VERSION, levelHash: levelHash(phys), device: DeviceTag.Unknown, flags: 0, nTicks: qs.length }, qs));
}

/** Simulates and summarises a q sequence the way golden_replays.json stores it. */
export function expectOf(phys: LevelPhysics, qs: Int8Array): GoldenExpect {
  const events: Record<string, number> = {};
  const r: ReplayResult = simulateReplay(phys, qs, {
    onTick(_t, _s, ev) {
      for (let i = 0; i < ev.n; i++) {
        const k = String(ev.kind[i]);
        events[k] = (events[k] ?? 0) + 1;
      }
    },
  });
  return {
    status: r.status,
    ticks: r.ticks,
    score: r.score,
    minD2: f64hex(r.minD2),
    peakF: f64hex(r.peakF),
    crash: r.crash
      ? { kind: r.crash.kind, wall: r.crash.wall, px: f64hex(r.crash.px), py: f64hex(r.crash.py), d2: f64hex(r.crash.d2) }
      : null,
    stateHash: r.stateHash,
    events,
  };
}

/** Regenerates a bot's q sequence (null for recorded entries). */
export function botReplay(def: BotDef, phys: LevelPhysics): Int8Array | null {
  return def.make ? runBot(phys, def.make(phys), def.maxTicks) : null;
}

/**
 * Checks every stored replay against this engine: the re-simulation summary (incl. stateHash) must equal the
 * stored one, the replay header must carry the level's hash, and each bot must regenerate exactly the stored
 * q sequence. Returns human-readable mismatches (empty = pass).
 */
export function checkGolden(g: GoldenFile, opts: { regenerateBots: boolean } = { regenerateBots: true }): string[] {
  const bad: string[] = [];
  if (g.sim !== SIM_VERSION) bad.push(`golden made with sim ${g.sim}, running sim ${SIM_VERSION}`);
  if (g.replays.length !== GOLDEN_BOTS.length) bad.push(`expected ${GOLDEN_BOTS.length} replays, file has ${g.replays.length}`);
  for (const e of g.replays) {
    const phys = g.levels[e.level];
    if (!phys) {
      bad.push(`${e.id}: no physics for level ${e.level}`);
      continue;
    }
    let qs: Int8Array;
    try {
      const d = decodeReplay(b64urlDecode(e.replay));
      if (d.h.levelHash !== levelHash(phys)) bad.push(`${e.id}: header hash ${d.h.levelHash} != ${levelHash(phys)}`);
      qs = d.qs;
    } catch (err) {
      bad.push(`${e.id}: undecodable replay (${String(err)})`);
      continue;
    }
    const got = expectOf(phys, qs);
    if (JSON.stringify(got) !== JSON.stringify(e.expect)) {
      bad.push(`${e.id}: got ${JSON.stringify(got)} want ${JSON.stringify(e.expect)}`);
    }
    if (opts.regenerateBots) {
      const def = GOLDEN_BOTS.find((b) => b.id === e.id);
      if (!def) {
        bad.push(`${e.id}: unknown bot`);
        continue;
      }
      const again = botReplay(def, phys);
      if (again && replayText(phys, again) !== e.replay) bad.push(`${e.id}: bot ${def.bot} produced a different q sequence`);
    }
  }
  return bad;
}
