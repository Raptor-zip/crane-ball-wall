export interface GoldenExpect {
  status: number; ticks: number; score: number | null;
  minD2: string; peakF: string; // float64 bit patterns (minD2 may be +Infinity)
  crash: { kind: number; wall: number; px: string; py: string; d2: string } | null;
  stateHash: number;
  events: Record<string, number>; // event kind -> count (documentation / coverage)
}
export interface GoldenEntry { id: string; level: string; bot: string; maxTicks: number; replay: string; expect: GoldenExpect }
export interface GoldenFile { format: 1; sim: number; about: string; levels: Record<string, LevelPhysics>; replays: GoldenEntry[] }

type BotDef = { id: string; level: string; bot: string; maxTicks: number; make: ((p: LevelPhysics) => Policy) | null };

